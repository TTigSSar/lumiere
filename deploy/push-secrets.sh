#!/usr/bin/env bash
# Copies the runtime secrets to the demo server (run locally from Git Bash, repo root or anywhere).
#   - /opt/lumiere/app.env                     built from the local .env (allow-listed keys only), root 600
#   - /opt/lumiere/secrets/service-account.json  Google key, owned by the container user (UID 1654), mode 400
# Never prints a secret value. Needs Tigran's approval like any server change.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
HOST="${LUMIERE_HOST:-root@91.98.170.128}"
KEY="${LUMIERE_SSH_KEY:-C:/Users/tigra/secrets/lumiere/lumiere_demo_ed25519}"
SA_JSON="${LUMIERE_SA_JSON:-C:/Users/tigra/secrets/lumiere/service-account.json}"
ENV_FILE="$REPO_ROOT/.env"
APP_UID=1654   # user "app" in mcr.microsoft.com/dotnet/aspnet:8.0
SSH_OPTS=(-i "$KEY" -o StrictHostKeyChecking=accept-new -o BatchMode=yes)

REQUIRED_KEYS=(TOOL_SHARED_SECRET SLOT_SIGNING_KEY GOOGLE_CALENDAR_ID TELEGRAM_BOT_TOKEN TELEGRAM_STAFF_CHAT_ID)

[ -f "$ENV_FILE" ] || { echo "missing $ENV_FILE" >&2; exit 1; }
[ -f "$SA_JSON" ] || { echo "missing service-account JSON (LUMIERE_SA_JSON)" >&2; exit 1; }

umask 077
TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT

# First non-empty value per key wins — same rule as src/Lumiere.Api/DotEnv.cs.
value_of() {
  awk -v k="$1" '
    { sub(/\r$/, "") }
    /^[[:space:]]*#/ { next }
    {
      i = index($0, "="); if (i == 0) next
      key = $0; sub(/=.*/, "", key); gsub(/^[[:space:]]+|[[:space:]]+$/, "", key)
      if (key != k) next
      v = substr($0, i + 1); gsub(/^[[:space:]]+|[[:space:]]+$/, "", v)
      gsub(/^["\047]+|["\047]+$/, "", v)
      if (v != "") { print v; exit }
    }' "$ENV_FILE"
}

{
  echo "# Generated by deploy/push-secrets.sh — do not edit on the server."
  for k in "${REQUIRED_KEYS[@]}"; do
    v="$(value_of "$k")"
    [ -n "$v" ] || { echo "missing or empty $k in .env" >&2; exit 1; }
    printf '%s=%s\n' "$k" "$v"
  done
  echo "GOOGLE_SERVICE_ACCOUNT_KEY_PATH=/run/secrets/service-account.json"
  echo "DATA_DIR=/data"
} > "$TMP"
echo "app.env built with keys: ${REQUIRED_KEYS[*]} GOOGLE_SERVICE_ACCOUNT_KEY_PATH DATA_DIR"

echo "==> copying app.env"
scp "${SSH_OPTS[@]}" -q "$TMP" "$HOST:/opt/lumiere/app.env.new"
ssh "${SSH_OPTS[@]}" "$HOST" 'chown root:root /opt/lumiere/app.env.new && chmod 600 /opt/lumiere/app.env.new && mv -f /opt/lumiere/app.env.new /opt/lumiere/app.env && ls -l /opt/lumiere/app.env'

echo "==> copying service-account.json"
scp "${SSH_OPTS[@]}" -q "$SA_JSON" "$HOST:/opt/lumiere/secrets/service-account.json.new"
ssh "${SSH_OPTS[@]}" "$HOST" "chown $APP_UID:$APP_UID /opt/lumiere/secrets/service-account.json.new && chmod 400 /opt/lumiere/secrets/service-account.json.new && mv -f /opt/lumiere/secrets/service-account.json.new /opt/lumiere/secrets/service-account.json && ls -l /opt/lumiere/secrets/service-account.json"

echo "==> secrets in place (values not shown). Restart the app to pick up changes: deploy/deploy.sh"
